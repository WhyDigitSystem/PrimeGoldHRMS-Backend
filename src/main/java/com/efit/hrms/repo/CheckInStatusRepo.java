	@Query(nativeQuery = true, value =
	        "WITH\r\n"
	        + "MonthRange AS (\r\n"
	        + "    SELECT\r\n"
	        + "        MAKEDATE(2025, 1) + INTERVAL (?2 - 1) MONTH AS start_date,\r\n"
	        + "        LAST_DAY(MAKEDATE(2025, 1) + INTERVAL (?2 - 1) MONTH) AS end_date\r\n"
	        + "),\r\n"
	        + "Numbers AS (\r\n"
	        + "    SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4\r\n"
	        + "    UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9\r\n"
	        + "    UNION ALL SELECT 10 UNION ALL SELECT 11 UNION ALL SELECT 12 UNION ALL SELECT 13 UNION ALL SELECT 14\r\n"
	        + "    UNION ALL SELECT 15 UNION ALL SELECT 16 UNION ALL SELECT 17 UNION ALL SELECT 18 UNION ALL SELECT 19\r\n"
	        + "    UNION ALL SELECT 20 UNION ALL SELECT 21 UNION ALL SELECT 22 UNION ALL SELECT 23 UNION ALL SELECT 24\r\n"
	        + "    UNION ALL SELECT 25 UNION ALL SELECT 26 UNION ALL SELECT 27 UNION ALL SELECT 28 UNION ALL SELECT 29\r\n"
	        + "    UNION ALL SELECT 30 UNION ALL SELECT 31\r\n"
	        + "),\r\n"
	        + "DateRange AS (\r\n"
	        + "    SELECT DATE_ADD(start_date, INTERVAL n DAY) AS entrydate\r\n"
	        + "    FROM MonthRange CROSS JOIN Numbers\r\n"
	        + "    WHERE DATE_ADD(start_date, INTERVAL n DAY) <= LEAST(end_date, CURDATE())\r\n"
	        + "),\r\n"
	        + "RawData AS (\r\n"
	        + "    SELECT checkindate, empcode, entrytime, createdon, status, approvalstatus\r\n"
	        + "    FROM checkin\r\n"
	        + "    WHERE orgid = ?3 AND branch = ?4 AND status IN ('In','Out')\r\n"
	        + "    \r\n"
	        + "    UNION ALL\r\n"
	        + "    \r\n"
	        + "    SELECT checkindate, empcode, entrytime, createdon, status, approvalstatus\r\n"
	        + "    FROM checkinoutadjustment\r\n"
	        + "    WHERE orgid = ?3 AND branch = ?4 AND status IN ('In','Out') AND approvalstatus IN ('Approved','PENDING')\r\n"
	        + "),\r\n"
	        + "Filtered AS (\r\n"
	        + "    SELECT * FROM RawData WHERE empcode = ?1\r\n"
	        + "),\r\n"
	        + "FirstIn AS (\r\n"
	        + "    SELECT checkindate, empcode, MIN(entrytime) AS first_in\r\n"
	        + "    FROM Filtered\r\n"
	        + "    WHERE status = 'In'\r\n"
	        + "    GROUP BY checkindate, empcode\r\n"
	        + "),\r\n"
	        + "LastOut AS (\r\n"
	        + "    SELECT checkindate, empcode, entrytime AS last_out\r\n"
	        + "    FROM (\r\n"
	        + "        SELECT *, ROW_NUMBER() OVER (\r\n"
	        + "            PARTITION BY checkindate, empcode\r\n"
	        + "            ORDER BY createdon DESC\r\n"
	        + "        ) AS rn\r\n"
	        + "        FROM Filtered\r\n"
	        + "        WHERE status = 'Out'\r\n"
	        + "    ) x\r\n"
	        + "    WHERE rn = 1\r\n"
	        + "),\r\n"
	        + "GrossCalc AS (\r\n"
	        + "    SELECT fi.checkindate, fi.empcode,\r\n"
	        + "           fi.first_in AS checkInTime,\r\n"
	        + "           lo.last_out AS checkOutTime,\r\n"
	        + "           CASE \r\n"
	        + "               WHEN TIMESTAMPDIFF(SECOND, fi.first_in, lo.last_out) < 0 THEN '00:00:00'\r\n"
	        + "               ELSE SEC_TO_TIME(TIMESTAMPDIFF(SECOND, fi.first_in, lo.last_out))\r\n"
	        + "           END AS gross_hours\r\n"
	        + "    FROM FirstIn fi\r\n"
	        + "    LEFT JOIN LastOut lo USING (checkindate, empcode)\r\n"
	        + "),\r\n"
	        + "PairedIO AS (\r\n"
	        + "    SELECT i.checkindate, i.empcode,\r\n"
	        + "           TIMESTAMPDIFF(SECOND, i.entrytime, o.entrytime) AS secs\r\n"
	        + "    FROM (\r\n"
	        + "        SELECT *,\r\n"
	        + "            ROW_NUMBER() OVER (\r\n"
	        + "                PARTITION BY checkindate, empcode\r\n"
	        + "                ORDER BY createdon\r\n"
	        + "            ) AS rn\r\n"
	        + "        FROM Filtered\r\n"
	        + "    ) i\r\n"
	        + "    JOIN (\r\n"
	        + "        SELECT *,\r\n"
	        + "            ROW_NUMBER() OVER (\r\n"
	        + "                PARTITION BY checkindate, empcode\r\n"
	        + "                ORDER BY createdon\r\n"
	        + "            ) AS rn\r\n"
	        + "        FROM Filtered\r\n"
	        + "    ) o\r\n"
	        + "    USING (checkindate, empcode)\r\n"
	        + "    WHERE i.status = 'In' AND o.status = 'Out' AND o.rn = i.rn + 1\r\n"
	        + "),\r\n"
	        + "EffectiveDurations AS (\r\n"
	        + "    SELECT checkindate, empcode,\r\n"
	        + "           CASE \r\n"
	        + "               WHEN SUM(secs) < 0 THEN '00:00:00'\r\n"
	        + "               ELSE SEC_TO_TIME(SUM(secs))\r\n"
	        + "           END AS effective_hours\r\n"
	        + "    FROM PairedIO\r\n"
	        + "    GROUP BY checkindate, empcode\r\n"
	        + "),\r\n"
	        + "Leaves AS (\r\n"
	        + "    SELECT leavedate\r\n"
	        + "    FROM approvalleaves\r\n"
	        + "    WHERE employeecode = ?1 AND branchcode = ?5 AND orgid = ?3\r\n"
	        + "    AND leavedate BETWEEN (SELECT start_date FROM MonthRange)\r\n"
	        + "                     AND (SELECT end_date FROM MonthRange)\r\n"
	        + "),\r\n"
	        + "HolidayList AS (\r\n"
	        + "    SELECT holidaydate\r\n"
	        + "    FROM holidays\r\n"
	        + "    WHERE branchcode = ?5 AND orgid = ?3\r\n"
	        + "    AND holidaydate BETWEEN (SELECT start_date FROM MonthRange)\r\n"
	        + "                       AND (SELECT end_date FROM MonthRange)\r\n"
	        + "),\r\n"
	        + "WeekOffs AS (\r\n"
	        + "    SELECT d.entrydate AS weekoffdate\r\n"
	        + "    FROM DateRange d\r\n"
	        + "    JOIN companyweekoff wo ON DAYNAME(d.entrydate) = wo.weekoffdays\r\n"
	        + "    JOIN branch b ON wo.companyid = b.orgid AND b.branchcode = ?5\r\n"
	        + "),\r\n"
	        + "LatestApproval AS (\r\n"
	        + "    SELECT checkindate, empcode, approvalstatus\r\n"
	        + "    FROM (\r\n"
	        + "        SELECT checkindate, empcode, approvalstatus,\r\n"
	        + "               ROW_NUMBER() OVER (\r\n"
	        + "                   PARTITION BY checkindate, empcode\r\n"
	        + "                   ORDER BY createdon DESC\r\n"
	        + "               ) AS rn\r\n"
	        + "        FROM Filtered\r\n"
	        + "        WHERE approvalstatus IS NOT NULL\r\n"
	        + "    ) x\r\n"
	        + "    WHERE rn = 1\r\n"
	        + "),\r\n"
	        + "FinalAttendance AS (\r\n"
	        + "    SELECT\r\n"
	        + "        d.entrydate,\r\n"
	        + "        ?1 AS empcode,\r\n"
	        + "        COALESCE(g.checkInTime, '00:00:00') AS checkInTime,\r\n"
	        + "        COALESCE(g.checkOutTime, '00:00:00') AS checkOutTime,\r\n"
	        + "        CASE\r\n"
	        + "            WHEN g.checkInTime IS NOT NULL THEN 'Present'\r\n"
	        + "            WHEN l.leavedate IS NOT NULL THEN 'Leave'\r\n"
	        + "            WHEN h.holidaydate IS NOT NULL THEN 'Holiday'\r\n"
	        + "            WHEN w.weekoffdate IS NOT NULL THEN 'WeekOff'\r\n"
	        + "            ELSE 'Absent'\r\n"
	        + "        END AS attendancestatus,\r\n"
	        + "        COALESCE(g.gross_hours, '00:00:00') AS grosshours,\r\n"
	        + "        COALESCE(e.effective_hours, '00:00:00') AS effectivehours,\r\n"
	        + "        a.approvalstatus AS approvalstatus\r\n"
	        + "    FROM DateRange d\r\n"
	        + "    LEFT JOIN GrossCalc g ON g.checkindate = d.entrydate\r\n"
	        + "    LEFT JOIN EffectiveDurations e ON e.checkindate = d.entrydate\r\n"
	        + "    LEFT JOIN Leaves l ON l.leavedate = d.entrydate\r\n"
	        + "    LEFT JOIN HolidayList h ON h.holidaydate = d.entrydate\r\n"
	        + "    LEFT JOIN WeekOffs w ON w.weekoffdate = d.entrydate\r\n"
	        + "    LEFT JOIN LatestApproval a ON a.checkindate = d.entrydate AND a.empcode = ?1\r\n"
	        + ")\r\n"
	        + "SELECT *\r\n"
	        + "FROM FinalAttendance\r\n"
	        + "WHERE attendancestatus IN ('Present', 'Absent')\r\n"
	        + "ORDER BY entrydate DESC;\r\n"
	        + "\r\n"
	        + "\r\n"
	        + ""
	)
	List<Map<String, Object>> findByEmpcode(
	    String empcode, 
	    int month, 
	    String orgId, 
	    String branch, 
	    String branchCode
	);


